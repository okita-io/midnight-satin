function slideX(index) {
  return index * (SLIDE_W + SLIDE_GAP);
}

function slideFrame(id, name, index, children) {
  return {
    type: "frame",
    id,
    name,
    x: slideX(index),
    y: 0,
    width: SLIDE_W,
    height: SLIDE_H,
    fill: "$color.void",
    layout: "none",
    clip: true,
    children,
  };
}

